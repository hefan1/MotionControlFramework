def rect(x, y, w, h, fill='white', stroke=LINE, r=5):
    """按左上角坐标绘制文档卡片或界面控件。"""
    C.setFillColor(colors.toColor(fill))
    C.setStrokeColor(colors.toColor(stroke))
    C.setLineWidth(0.65)
    C.roundRect(x, H-y-h, w, h, r, fill=1, stroke=1)


def label(x, y, value, size=10, color=NAVY, bold=False):
    """绘制单行中文文字，不承担正文分页。"""
    C.setFont('CNB' if bold else 'CN', size)
    C.setFillColor(colors.toColor(color))
    C.drawString(x, H-y-size, value)


def para(x, y, w, value, size=10.5, color=NAVY, bold=False, record=True):
    """绘制自动换行正文并检查页脚边界，同时保留可编辑正文。"""
    style = ParagraphStyle('body', fontName='CNB' if bold else 'CN', fontSize=size,
                           leading=size*1.55, wordWrap='CJK', textColor=colors.HexColor(color))
    p = Paragraph(escape(value).replace('\n', '<br/>'), style)
    _, h = p.wrap(w, 1000)
    if y+h > H-36:
        raise ValueError(f'第 {PAGE} 页正文越界：{value[:35]}，bottom={y+h:.1f}')
    p.drawOn(C, x, H-y-h)
    if record:
        MD.extend([value, ''])
    return y+h


def block(x, y, w, title, body, tint=LIGHT, h=None):
    """绘制一段有标题的设计说明，按内容自动确定卡片高度。"""
    body_style = ParagraphStyle('card', fontName='CN', fontSize=10.2, leading=16, wordWrap='CJK')
    p = Paragraph(escape(body).replace('\n', '<br/>'), body_style)
    _, ph = p.wrap(w-24, 1000)
    height = h or ph+46
    rect(x, y, w, height, tint)
    label(x+12, y+10, title, 12, BLUE, True)
    para(x+12, y+34, w-24, body, 10.2)
    return y+height


def button(x, y, text, w=90, primary=False, disabled=False):
    """绘制按钮示意，区分主操作、普通操作和禁用。"""
    fill = '#E8EDF3' if disabled else BLUE if primary else 'white'
    rect(x, y, w, 27, fill, LINE if not primary else BLUE, 4)
    label(x+9, y+6, text, 9.3, '#9AA4B1' if disabled else 'white' if primary else NAVY)


def field(x, y, caption, value, w=220, dropdown=False):
    """绘制带标签的只读或编辑字段示意。"""
    label(x, y, caption, 9.6, MUTED)
    rect(x, y+18, w, 29, 'white', LINE, 3)
    label(x+9, y+25, value, 10)
    if dropdown:
        label(x+w-18, y+26, 'v', 9, MUTED)


def table(x, y, w, headers, rows, widths=None, size=9.5):
    """绘制可换行表格并拒绝跨过页脚，保留 Markdown 数据表。"""
    widths = widths or [1]*len(headers)
    widths = [w*v/sum(widths) for v in widths]
    style = ParagraphStyle('cell', fontName='CN', fontSize=size, leading=size*1.5,
                           wordWrap='CJK', textColor=colors.HexColor(NAVY))
    data = [[Paragraph(escape(str(v)).replace('\n', '<br/>'), style) for v in row] for row in [headers]+rows]
    t = Table(data, colWidths=widths, repeatRows=1)
    t.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,0), colors.HexColor('#EAF1FA')),
        ('ROWBACKGROUNDS', (0,1), (-1,-1), [colors.white, colors.HexColor('#F8FAFD')]),
        ('VALIGN', (0,0), (-1,-1), 'TOP'),
        ('GRID', (0,0), (-1,-1), .5, colors.HexColor(LINE)),
        ('LEFTPADDING',(0,0),(-1,-1),8),('RIGHTPADDING',(0,0),(-1,-1),8),
        ('TOPPADDING',(0,0),(-1,-1),7),('BOTTOMPADDING',(0,0),(-1,-1),7)]))
    _, h = t.wrap(w, 1000)
    if y+h > H-36:
        raise ValueError(f'第 {PAGE} 页表格越界：{headers}，bottom={y+h:.1f}')
    t.drawOn(C, x, H-y-h)
    MD.append('| '+' | '.join(headers)+' |')
    MD.append('| '+' | '.join(['---']*len(headers))+' |')
    MD.extend('| '+' | '.join(str(v).replace('\n',' / ') for v in row)+' |' for row in rows)
    MD.append('')
    return y+h


def image(x, y, w, h, filename, record=True):
    """等比例嵌入 AI 概念稿，不裁切或改写原图。"""
    path = ASSETS / filename
    iw, ih = Image.open(path).size
    ratio = min(w/iw, h/ih)
    dw, dh = iw*ratio, ih*ratio
    C.drawImage(str(path), x+(w-dw)/2, H-y-dh, dw, dh, mask='auto')
    if record:
        MD.extend([f'![AI 工作区概念稿](assets/{filename})', ''])


def footer():
    """绘制页脚，统一标明讨论稿与代码基线。"""
    C.setStrokeColor(colors.HexColor(LINE))
    C.line(30, 30, W-30, 30)
    label(30, H-24, 'UI 交互设计讨论稿 V1  |  代码基线 348f8c3  |  2026-10-24', 7.7, MUTED)
    label(W-75, H-24, f'{PAGE:02d} / 24', 8, MUTED)


def page(title, subtitle, badge='设计建议'):
    """开始固定版式的一页，并在上一页写入页脚。"""
    global PAGE
    if PAGE:
        footer()
        C.showPage()
    PAGE += 1
    C.bookmarkPage(f'page-{PAGE}')
    C.addOutlineEntry(title, f'page-{PAGE}', level=0, closed=False)
    C.setFillColor(colors.white)
    C.rect(0,0,W,H,fill=1,stroke=0)
    C.setFillColor(colors.HexColor(BLUE))
    C.rect(0,H-7,W,7,fill=1,stroke=0)
    label(30, 20, 'MotionControlFramework  /  现场操作与工程调试', 8.5, MUTED)
    label(W-140, 20, badge, 8.5, BLUE, True)
    label(30, 42, title, 22, NAVY, True)
    para(30, 75, W-60, subtitle, 10, MUTED, record=False)
    MD.extend([f'## {PAGE:02d}  {title}', '', f'状态：{badge}。{subtitle}', ''])


