def arrow(x1, y1, x2, y2):
    """绘制数据或操作方向箭头，避免依赖特殊箭头字体。"""
    C.setStrokeColor(colors.HexColor(BLUE))
    C.setLineWidth(1.2)
    C.line(x1,H-y1,x2,H-y2)
    if abs(x2-x1) >= abs(y2-y1):
        d=1 if x2>x1 else -1
        C.line(x2,H-y2,x2-6*d,H-y2+3)
        C.line(x2,H-y2,x2-6*d,H-y2-3)
    else:
        d=1 if y2>y1 else -1
        C.line(x2,H-y2,x2-3,H-y2+6*d)
        C.line(x2,H-y2,x2+3,H-y2+6*d)


